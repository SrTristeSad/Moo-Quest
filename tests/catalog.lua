package.path="./?.lua;./?/init.lua;"..package.path
local C=require("src.game.catalog")
assert(#C.groups==14,"group count")
assert(#C.projectiles==6,"projectile count")
assert(#C.weapons==16,"weapon count")
assert(#C.items==23,"placeable and consumable item count")
assert(#C.hats==49,"hat count")
assert(#C.accessories==21,"accessory count")
local hammer=C.weaponById(0)
assert(hammer.name=="tool hammer" and hammer.range==65 and hammer.speed==300 and hammer.gather==1)
assert(C.weaponById(15).name=="musket")
local wall=C.itemById(3)
assert(wall.id==3 and wall.name=="wood wall" and wall.scale==50 and wall.health==380)
assert(wall.groupId==1 and wall.req[1]=="wood" and wall.req[2]==10)
assert(C.itemById(6).name=="spikes" and C.itemById(10).name=="windmill")
assert(C.groupById(1).limit==30)
assert(C.itemById(5).pre==4,"reference postprocessing of item pre")
assert(C.itemById(0).consume==true,"the consume function still requires a Lua implementation")
assert(C.hats[#C.hats].name~="")
assert(C.accessories[1].name=="Snowball")
assert(C.itemById(-1)==nil and C.itemById(23)==nil)
assert(C.weaponById(16)==nil and C.groupById(14)==nil)
for i,item in ipairs(C.items) do
  assert(item.id==i-1,"item order is part of the reference protocol")
  assert(type(item.groupId)=="number")
  assert(C.groupById(item.groupId).id==item.groupId)
end
print("Lua reference catalog integrity tests passed")
