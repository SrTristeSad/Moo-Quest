package.path="./?.lua;./?/init.lua;"..package.path
local J=require("src.net.json")
local raw='{"clan":null,"invites":[{"clan":"ABCD","by":"Player"}],"role":"owner","closed":true,"count":12,"message":"a\\nb","name":"\\u00E9"}'
local data=assert(J.decode(raw))
assert(data.clan==J.null and data.invites[1].clan=="ABCD")
assert(data.closed==true and data.role=="owner" and data.count==12)
assert(data.message=="a\nb" and data.name=="é")
local encoded=assert(J.encode({name="ABCD",accept=false,n=7,open=true,list={"a","b"}}))
local again=assert(J.decode(encoded))
assert(again.accept==false and again.open==true and again.list[2]=="b")
assert(not J.decode('{"x":true trailing}'))
assert(not J.decode('{"x":1,}'))
assert(not J.decode('{"bad":"\\uD800"}'))
assert(not J.decode('["a" "b"]'))
assert(not J.decode('["x",'))
assert(not J.decode(string.rep(" ",131073)))
assert(not J.encode({x=math.huge}))
local t={};t.self=t;assert(not J.encode(t))
local star=assert(J.decode('{"symbol":"\\uD83D\\uDE80"}'))
assert(#star.symbol==4)
print("safe JSON codec and persistent clan payload format passed")
