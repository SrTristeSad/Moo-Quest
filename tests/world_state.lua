assert(w:animalKind(0).health==510, "Node A catalog must be authoritative")
assert(w:animalKind(4).name=="Wolf", "fallback stays for older original builds")
assert(#w.teams==1)
assert(not w:apply("A",{"invalid-payload"}))

assert(w:apply("C",{42}) and w.spawned and w.sid==42)
assert(w.inventory.weapons[1]==0 and #w.inventory.items==4)
assert(w.inventory.items[1]==0 and w.inventory.items[4]==10)

assert(w:apply("S",{6,3}) and w.itemCounts[6]==3)
assert(w:apply("S",{6,2}) and w.itemCounts[6]==2)

assert(w.maxXP==300 and w.upgradeAge==2)
assert(w:apply("D",{{"socket-1",42,"Player",100,200,1.5,85,100,35,0}}))
assert(w:localPlayer().name=="Player" and w:localPlayer().health==85)
assert(w:apply("a",{{42,105,205,157,43,600,700,0},{42,-1,0,0,"Blue",0,0,0,0,0},{}}))
assert(w:localPlayer().x==105 and w:localPlayer().dir==1.57)
assert(w:localPlayer().team=="Blue" and w.players[43].x==600)
assert(w:apply("H",{{12,500,600,0,150,0,0,-1,13,700,800,0,85,2,0,-1}}))
assert(w.objects[12].type==0 and w.objects[13].type==2)
assert(w:apply("I",{{77,4,800,900,100,300,0,0},{}}))
assert(w.animals[77].index==4 and w.animals[77].dir==1)
assert(w:apply("N",{"wood",40,1}) and w.resources.wood==40)
assert(w.resourceGain.wood==nil, "first authoritative total is not a pickup")
assert(w:apply("N",{"wood",5,0}) and w.resources.wood==45)
assert(w.resourceGain.wood and w.resourceGain.wood.amount==5)
assert(w:apply("N",{"kills",2,1}) and w.resources.kills==2)
w:update(1.6)
assert(w.resourceGain.wood==nil, "recent resource pickup must expire")
assert(w:apply("O",{42,65}) and w:localPlayer().health==65)
assert(w:apply("6",{42,"Ola"}) and w:localPlayer().chatMessage=="Ola")
assert(w:localPlayer().chatCountdown==3000)
w:update(0.5)
assert(w:localPlayer().chatCountdown==2500)
w:update(2.5)
assert(w:localPlayer().chatCountdown==0)
assert(w:apply("7",{{50,80,100,120}}))
assert(#w.minimapData==4 and w.minimapData[4]==120)
assert(w:apply("9",{200,300}) and #w.mapPings==1)
w:update(0.4)
assert(math.abs(w.mapPings[1].scale-20)<0.001)
w:update(0.5)
assert(#w.mapPings==0,"map ping fadeout must follow JavaScript reference")
assert(w:apply("K",{42,1,0}) and w:localPlayer().animSpeed==300)
assert(w:apply("J",{77}) and w.animals[77].animSpeed==600)
assert(w:apply("G",{{42,"Player",123,43,"Guest",22}}) and #w.leaderboard==2)
assert(w:apply("I",{{},{77}}) and w.animals[77]==nil)
assert(w:apply("Q",{12}) and w.objects[12]==nil)
assert(w:apply("a",{{42,105,205,157},{},{43}}) and w.players[43]==nil)
assert(w:apply("X",{20,30,0,100,1,0,0,99}))
assert(w.projectiles[99] and w.projectiles[99].x==20)
w:update(0.05) -- projectile does not move on the first client tick
assert(w.projectiles[99].x==20)
w:update(0.05)
assert(w.projectiles[99].x==70 and w.projectiles[99].range==50)
assert(w:apply("Y",{99,20}) and w.projectiles[99].range==20)
w:update(0.05)
assert(w.projectiles[99]==nil)
assert(w:apply("H",{{111,330,450,0,50,1,6,42}}))
-- Real Node turret-shot M must turn the structure and apply the same
-- visual recoil as the archived browser: opposite the firing angle.
assert(w:apply("H",{{112,340,450,0,43,0,17,42}}))
local turret=w.objects[112]
assert(w:apply("M",{112,0}) and turret.dir==0)
assert(math.abs(turret.wiggleX+10)<0.00001 and
  math.abs(turret.wiggleY)<0.00001,
  "turret should recoil 10 world units opposite shot direction")
w:update(0.1)
assert(turret.wiggleX<0 and turret.wiggleX>-10,
  "turret recoil should decay, not remain permanently offset")
local before=turret.wiggleY or 0
assert(w:apply("M",{112,math.pi/2}))
assert(math.abs(turret.wiggleY-before+10)<0.00001,
  "turret must recoil toward negative Y when firing downward")
local recoilX,recoilY=turret.wiggleX,turret.wiggleY
assert(w:apply("M",{9999,0}) and
  turret.wiggleX==recoilX and turret.wiggleY==recoilY,
  "M for an unknown Node object must not create a phantom turret")
assert(w:apply("R",{42}) and w.objects[111]==nil and w.objects[112]==nil)
assert(w:apply("P",{}) and w.dead and not w.spawned)
assert(w.lastDeath and w.lastDeath.x==105 and w.lastDeath.y==205)
assert(w:apply("C",{42}) and w.spawned and not w.dead)
assert(w:localPlayer()==nil, "new life must wait for a fresh server D")
assert(w:apply("D",{{"socket-1",42,"Player",360,480,0,100,100,35,0}}))
assert(w:localPlayer().x==360 and w:localPlayer().y==480)
assert(w.lastDeath.x==105 and w.lastDeath.y==205)
print("authoritative Node packet game-state tests passed")
