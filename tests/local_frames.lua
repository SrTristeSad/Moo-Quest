package.path="./?.lua;./?/init.lua;"..package.path
local Frames=require("src.net.local_frames")
local a=Frames.encode({"move",math.pi/4})
local b=Frames.encode({"join","Guest"})
local messages,left=Frames.decode(a:sub(1,2))
assert(messages and #messages==0 and #left==2)
messages,left=Frames.decode(left..a:sub(3)..b)
assert(messages and #messages==2 and left=="")
assert(messages[1][1]=="move" and messages[1][2]==math.pi/4)
assert(messages[2][2]=="Guest")
local invalid=string.char(255,255,255,255)
assert(Frames.decode(invalid)==nil)
assert(Frames.decode(string.char(0,0,0,1,0xc1))==nil)
print("local framed MessagePack tests passed")
