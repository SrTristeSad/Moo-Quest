package.path="./?.lua;./?/init.lua;"..package.path
local Adapter=require("src.net.node_protocol")
local Pack=require("src.protocol.msgpack")
local p=Adapter.new()
local function feed(name,args)
  -- This is the same transport shape returned by the Node native bridge.
  local wire={"event",name,args}
  wire=Pack.decode(Pack.encode(wire))
  return p:decode(wire)
end
local events=feed("A",{{teams={},animals={}}})
assert(events[1][1]=="world" and events[1][2]==14400)
events=feed("C",{7})
assert(events[1][1]=="welcome" and events[1][2]==7)
events=feed("D",{{"uuid-local",7,"Tester",4500,5400,0,100,100,35,0},true})
assert(events[1][1]=="players" and events[1][2][1][1]==7)
events=feed("a",{{7,4512,5420,157},{7,-1,0,0,Pack.null,0,0,0,0,0},{}})
assert(events[1][2][1][3]==4512)
assert(math.abs(events[1][2][1][5]-1.57)<0.000001)
events=feed("N",{"wood",37,1})
assert(events[1][1]=="status" and events[1][3]==37)
events=feed("H",{{11,4520,5420,0,150,0,Pack.null,-1}})
assert(events[1][1]=="object" and events[1][2]==11 and events[1][6]==0)
assert(events[1][7]==-1)
assert(#feed("H",{{11,4520,5420,0,150,0,Pack.null,-1}})==0,"deduplicated objects")
events=feed("I",{{4,0,4510,5420,170,400,3,0},{}})
assert(events[1][1]=="animals" and events[1][2][1][1]==4)
assert(events[1][2][1][6]==400)
events=feed("O",{7,62})
assert(events[1][1]=="players" and events[1][2][1][6]==62)
events=feed("Q",{11})
assert(events[1][1]=="remove_object" and events[1][2]==11)
events=feed("I",{{},{4}})
assert(events[1][1]=="animals" and #events[1][2]==0)
events=feed("P",{})
assert(events[1][1]=="players" and events[2][1]=="dead")
events=feed("D",{{"uuid-local",7,"Tester",4500,5400,0,100,100,35,0},true})
assert(events[1][2][1][7]==1,"respawn from authoritative D")
events=feed("E",{"uuid-local"})
assert(events[1][1]=="players" and #events[1][2]==0)
assert(#p:decode({"unexpected","C",{7}})==0,"reject unknown envelope")
print("Node.js original gameplay packet adapter tests passed")
