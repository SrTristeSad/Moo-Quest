import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { WebSocket } from 'ws';
import { Storage } from '../src/storage.js';
import { Auth } from '../src/auth.js';
import { Updates } from '../src/updates.js';
import { createHTTP } from '../src/http.js';
import { GameServer } from '../src/game.js';
const appRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
test('live HTTP + WebSocket: alpha protocol, movement, admin kick, persisted ban',async t=>{
  const previous=process.env.MOO_DEV_JSON;
  process.env.MOO_DEV_JSON='1';
  t.after(()=>{if(previous===undefined)delete process.env.MOO_DEV_JSON;else process.env.MOO_DEV_JSON=previous;});
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'mq-ws-live-'));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const storage=new Storage(root),auth=new Auth(),updates=new Updates(root,storage.dir,{manifestURL:null,publicKeyFile:null});
  const http=createHTTP({root:appRoot,storage,auth,updates});
  const game=new GameServer(http.server,storage);
  http.setGame(game);
  await new Promise(resolve=>http.server.listen(0,'127.0.0.1',resolve));
  t.after(async()=>{await game.stop();await new Promise(resolve=>http.server.close(resolve));});
  game.start();
  const url='ws://127.0.0.1:'+http.server.address().port+'/play';
  const ws=new WebSocket(url);
  const events=[];
  ws.on('message',raw=>events.push(JSON.parse(String(raw))));
  await new Promise((resolve,reject)=>{ws.once('open',resolve);ws.once('error',reject);});
  ws.send(JSON.stringify({kind:'join',name:'Testador'}));
  const until=Date.now()+1500;
  while(!events.some(x=>x.kind==='joined') && Date.now()<until) await new Promise(r=>setTimeout(r,10));
  const me=events.find(x=>x.kind==='joined');
  assert.ok(me?.id);
  assert.equal(game.room.players.size,1);
  ws.send(JSON.stringify({kind:'input',dx:1,dy:0,x:99999}));
  await new Promise(r=>setTimeout(r,100));
  assert.ok(game.room.players.get(me.id).x<game.room.size);
  const hash=game.room.players.get(me.id).ipHash;
  assert.match(hash,/^[0-9a-f]{64}$/);
  storage.data.bans[hash]={reason:'e2e ban'};storage.save();
  assert.equal(game.kick(me.id,'banned'),true);
  await new Promise(resolve=>ws.once('close',resolve));
  await assert.rejects(async()=>{
    const reconnect=new WebSocket(url);
    await new Promise((resolve,reject)=>{
      reconnect.once('open',resolve);
      reconnect.once('error',reject);
      reconnect.once('unexpected-response',(_,res)=>reject(new Error('rejected '+res.statusCode)));
      reconnect.once('close',()=>reject(new Error('socket closed')));
    });
  });
});
